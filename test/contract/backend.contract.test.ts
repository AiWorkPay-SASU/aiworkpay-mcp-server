import { createHash } from 'node:crypto';
import { readFileSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { accountSchema, approveSchema, missionSchema, transactionsSchema } from '../../src/api/schemas.js';
import { missionView, toAgentStatus } from '../../src/domain/missionStatus.js';

const DIR = join(dirname(fileURLToPath(import.meta.url)), 'fixtures');
const fixture = (name: string) => JSON.parse(readFileSync(join(DIR, `${name}.json`), 'utf8'));

describe('backend contract (fixtures generated by the Aiworkpay-v2 code)', () => {
  it('the copied fixtures are the ones the backend published (checksums)', () => {
    const manifest = JSON.parse(readFileSync(join(DIR, 'MANIFEST.json'), 'utf8')) as Record<string, string>;
    const files = readdirSync(DIR).filter((file) => file !== 'MANIFEST.json').sort();
    expect(files).toEqual(Object.keys(manifest).sort());
    for (const file of files) {
      expect(createHash('sha256').update(readFileSync(join(DIR, file), 'utf8')).digest('hex')).toBe(manifest[file]);
    }
  });

  it('parses a mission as an agent reads it, and keeps the overdue flag', () => {
    const overdue = missionSchema.parse(fixture('mission.agent.in_progress_overdue'));
    expect(overdue.status).toBe('IN_PROGRESS');
    expect((overdue as Record<string, unknown>).overdue).toBe(true);
    const delivered = missionSchema.parse(fixture('mission.agent.delivered'));
    expect((delivered as Record<string, unknown>).overdue).toBe(false);
    expect(delivered.attachments?.map((a) => a.kind)).toEqual(['PROOF']);
  });

  it('turns every mission fixture into an agent view without throwing, and maps its status', () => {
    for (const name of ['mission.agent.in_progress_overdue', 'mission.agent.delivered']) {
      const mission = missionSchema.parse(fixture(name));
      const view = missionView(mission as never);
      expect(view.status).toBe(toAgentStatus(mission.status));
      expect(typeof view.budget).toBe('number');
    }
    // A taken mission past its deadline is flagged and explained, never presented as canceled
    const late = missionView(missionSchema.parse(fixture('mission.agent.in_progress_overdue')) as never);
    expect(late.is_past_deadline).toBe(true);
    expect(late.status).toBe('in_progress');
    expect(late.next_action).toContain('deadline has passed');
    expect(late.next_action).toContain('does not cancel');
    const onTime = missionView(missionSchema.parse(fixture('mission.agent.in_progress_overdue')) as never, new Date('2019-01-01T00:00:00Z'));
    expect(onTime.next_action).not.toContain('deadline has passed');
  });

  it('parses the account and the ledger', () => {
    const account = accountSchema.parse(fixture('account'));
    expect(account.usage.remainingThisMonth).toBe(475);
    const ledger = transactionsSchema.parse(fixture('transactions'));
    expect(ledger.transactions[0]?.type).toBe('AGENT_PAYMENT');
  });

  it('reads the error envelope the way the client does (error, code, details, Retry-After)', () => {
    const notFound = fixture('error.not_found');
    expect(notFound.status).toBe(404);
    expect(typeof notFound.body.code).toBe('string');
    expect(typeof notFound.body.error).toBe('string');
    const limited = fixture('error.rate_limited');
    expect(limited.status).toBe(429);
    expect(limited.body.code).toBe('RATE_LIMITED');
    expect(Number(limited.body.details.retryAfterSeconds)).toBeGreaterThan(0);
  });

  it('keeps accepting the approve response with and without commission', () => {
    const mission = fixture('mission.agent.delivered');
    expect(approveSchema.safeParse({ mission, alreadyApproved: false, commission: { payworkerAmount: 22.5, platformFeeAmount: 2.5, transferStatus: 'SUCCEEDED' } }).success).toBe(true);
    expect(approveSchema.safeParse({ mission, alreadyApproved: true }).success).toBe(true);
  });
});
